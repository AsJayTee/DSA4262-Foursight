#!/usr/bin/env sh
# Run a batch of comparisons end to end, locally or on Ronin.
#
# This drives scripts/evaluate.py; it computes nothing itself and it is not
# shared infrastructure. Every line below is a command you could type by hand -
# the script exists so that a whole batch survives one arm failing, and so that
# a Ronin instance can be handed one command and left alone.
#
#   sh analysis/evaluation/run_batch.sh            # everything not yet done
#   sh analysis/evaluation/run_batch.sh groupA     # just one group
#   sh analysis/evaluation/run_batch.sh --list     # print the plan, run nothing
#
# Works in Git Bash on Windows and on a Ronin Ubuntu box: it finds the venv
# interpreter either way. Set M6A_DATA_DIR if the data is not in data/raw.
#
# DO NOT EDIT THIS FILE WHILE IT IS RUNNING. `sh` reads a script incrementally
# from a byte offset, so appending to it mid-run makes the shell resume at the
# wrong place. This bit twice on 2026-09-24 and the second time is the
# instructive one:
#
#   1. Editing the PLAN mid-run made the shell resume mid-line and die with a
#      syntax error - after all six arms had finished and logged to W&B.
#   2. Wrapping the body in `main()` fixed the body but NOT the tail: the file
#      grew while `main "$@"` was executing, so when the shell went back for the
#      next command its saved offset now pointed *inside* main's body, and it
#      re-ran the fragment. The batch printed its success line AND then a bogus
#      "FAILED:" with nothing after it, and exited 1 on a run where every arm
#      had passed.
#
# So the invocation below is `main "$@"; exit $?` on ONE line: both commands are
# parsed together, and the shell exits without ever seeking back into the file.
# That closes the hole. The habit is still the real fix - add arms, THEN start
# the batch, never the other way round.
#
# WHY IT DOES NOT STOP ON FAILURE. Ronin instances are terminated with nothing
# pulled off them (docs/decisions/0007), so a batch that dies on arm 2 of 6 and
# sits idle until someone notices has wasted the instance. Each arm is logged,
# failures are counted and named at the end, and the rest keep going. Every
# result is in W&B before the next arm starts.

set -u

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT" || exit 1

if [ -x .venv/bin/python ]; then
    PY=.venv/bin/python
elif [ -x .venv/Scripts/python.exe ]; then
    PY=.venv/Scripts/python.exe
else
    PY=$(command -v python3 || command -v python)
fi
[ -n "${PY:-}" ] || { echo "No python interpreter found. Create .venv first."; exit 1; }

LOGS="$ROOT/analysis/evaluation/logs"
mkdir -p "$LOGS"

# --------------------------------------------------------------------------
# The plan. One line per arm:  group | label | arguments to evaluate.py
#
# Ordered cheap-and-decisive first. Group C shares one hypothesis and the three
# arms attribute it to a structure, so run all three or none - a single one
# cannot say which graph is worth building.
# --------------------------------------------------------------------------
PLAN=$(cat <<'PLAN'
done|flank_x_depth|--config configs/quantiles_flank_depth_augmented.yaml --compare-features quantiles_v1
done|flank_vs_depthaug|--config configs/quantiles_flank_depth_augmented.yaml --compare-run psdwqobf
done|flank_ablation|--config configs/quantiles_flank.yaml --ablate
done|nbr_struct|--config configs/nbr_struct.yaml --compare-features quantiles_v1
done|nbr_signal|--config configs/nbr_signal.yaml --compare-features quantiles_v1
done|transcript|--config configs/transcript.yaml --compare-features quantiles_v1
done|transcript_robust|--config configs/transcript_robust.yaml --compare-with configs/transcript.yaml
groupF|crosssite_robust|--config configs/crosssite_robust.yaml --compare-with configs/quantiles_flank_depth_augmented.yaml
groupF|final_candidate|--config configs/final_candidate.yaml --compare-with configs/quantiles_flank_depth_augmented.yaml
groupB|coupling|--config configs/coupling.yaml --compare-features quantiles_v1
groupD|calib_prior_shift|--config configs/calibrated_prior_shift.yaml
groupD|calib_platt|--config configs/calibrated_platt.yaml
groupE|best_ablation|--config configs/quantiles_flank_depth_augmented.yaml --ablate
groupE|budget_450|--config configs/best_shorter.yaml --compare-with configs/quantiles_flank_depth_augmented.yaml
PLAN
)

main() {
    WANT=${1:-all}
    # "done" arms have already run; `all` deliberately skips them.
    [ "$WANT" = "all" ] && WANT_SKIP_DONE=1

    if [ "$WANT" = "--list" ]; then
        echo "$PLAN" | while IFS='|' read -r group label args; do
            printf '  %-8s %-20s %s\n' "$group" "$label" "$args"
        done
        exit 0
    fi

    STARTED=$(date +%s)
    FAILED=""
    COUNT=0

    echo "$PLAN" | {
        while IFS='|' read -r group label args; do
            [ "$group" = "done" ] && continue
            [ "$WANT" = "all" ] || [ "$WANT" = "$group" ] || continue
            COUNT=$((COUNT + 1))
            LOG="$LOGS/${label}.log"
            echo "=============================================================="
            echo "[$group] $label   ->  $LOG"
            echo "  $PY scripts/evaluate.py $args"
            echo "  started $(date -u '+%Y-%m-%dT%H:%M:%SZ')"
            ARM_START=$(date +%s)
            # shellcheck disable=SC2086
            if "$PY" scripts/evaluate.py $args >"$LOG" 2>&1; then
                echo "  OK in $((($(date +%s) - ARM_START) / 60)) min"
                grep -E "corrected \(quote this\)|is \+?-?0\.[0-9]+ (better|worse)" "$LOG" | tail -2
            else
                echo "  FAILED after $((($(date +%s) - ARM_START) / 60)) min - see $LOG"
                tail -15 "$LOG"
                FAILED="$FAILED $label"
            fi
        done

        echo "=============================================================="
        echo "batch done in $((($(date +%s) - STARTED) / 60)) min, $COUNT arm(s)"
        if [ -n "$FAILED" ]; then
            echo "FAILED:$FAILED"
            echo "Everything else is in W&B. Re-run only the failures."
            exit 1
        fi
        echo "All arms logged to W&B. Pull results with scripts/compare_runs.py."
    }
}

main "$@"; exit $?
