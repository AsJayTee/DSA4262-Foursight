#!/usr/bin/env bash
# m6Anet (pretrained HCT116_RNA002) on the SG-NEx sites glori_check.py grades, for A549, H9, HepG2.
#
#   nohup bash analysis/sgnex/run_m6anet_glori.sh > data/m6anet_glori/run.log 2>&1 &
#
# Needs data/m6anet_glori/keys_<line>.csv.gz (exported from glori_check.py's
# labelled sites), data/sgnex_runs/ (score_sgnex.py downloads), the project
# .venv and m6Anet's own venv (analysis/m6anet/run_ronin.sh setup).
#
# One inference per line at min_reads 1. m6Anet's official 20-read setting is
# the >= 20 subset of the same output: each site's probability depends only on
# its own reads, so a second run would reproduce those rows exactly.
#
# Sharded, because one m6Anet process uses ~6 cores whatever --n_processes says
# (the model step runs in the main process; workers only load data). Unsharded,
# A549 ran at ~57 sites/s and the three lines would have taken ~6.5 h on 64
# vCPUs; 8 shards per line at --n_processes 4 run at ~100 sites/s each. Each
# shard shares the line's data.json and reads only its slice of data.info.
# m6anet_glori_compare.py concatenates the shards' outputs.
#
# On 26 Oct the run itself went partly unsharded (A549 started as one process,
# its remaining sites were sharded later); the outputs are identical either way.
#
# DO NOT EDIT THIS FILE WHILE IT IS RUNNING (analysis/m6anet/run_ronin.sh says why).
set -euo pipefail
cd "$(dirname "$0")/../.."
W=data/m6anet_glori
LINES="A549 H9 HepG2"
SHARDS=8
stamp() { date +%H:%M:%S; }

for line in $LINES; do
  .venv/bin/python -u analysis/sgnex/m6anet_prep.py --line "$line" --keys "$W/keys_$line.csv.gz" \
    --out "$W/${line}_input" > "$W/prep_$line.log" 2>&1 &
done
wait
for line in $LINES; do
  [ -s "$W/${line}_input/data.info" ] || { echo "$(stamp) prep FAILED for $line: see $W/prep_$line.log"; exit 1; }
done

for line in $LINES; do
  info=$W/${line}_input/data.info
  total=$(($(wc -l < "$info") - 1)); per=$(( (total + SHARDS - 1) / SHARDS ))
  for i in $(seq 0 $((SHARDS - 1))); do
    d=$W/${line}_shard$i; mkdir -p "$d"; ln -sf "../${line}_input/data.json" "$d/data.json"
    { head -1 "$info"; tail -n +2 "$info" | sed -n "$((i * per + 1)),$(((i + 1) * per))p"; } > "$d/data.info"
    analysis/m6anet/.venv/bin/python -u analysis/m6anet/infer_low_depth.py --input_dir "$d" \
      --out_dir "$W/${line}_out_shard$i" --pretrained_model HCT116_RNA002 --n_processes 4 --min_reads 1 \
      > "$W/infer_${line}_shard$i.log" 2>&1 &
  done
  echo "$(stamp) started $line in $SHARDS shards"
  # One line at a time: 8 shards already fill the machine.
  wait
  echo "$(stamp) done $line"
done
echo "$(stamp) ALL_DONE"
